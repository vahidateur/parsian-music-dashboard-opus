/**
 * Writing the dataset artifact — the deterministic generator.
 *
 * SOURCE OF TRUTH, IN BOTH DIRECTIONS
 *
 * `createSeedDataset()` builds the canonical dataset; this module serializes it
 * into `data/dataset/`. The equivalence suite re-runs `buildDatasetArtifact()`
 * and compares the result with the files committed in the repository, so:
 *
 *   - editing a committed member file without regenerating ⇒ the suite fails;
 *   - changing the seed without regenerating ⇒ the suite fails;
 *   - regenerating ⇒ byte-identical output, because nothing here reads a clock
 *     or a random source. (The manifest's `createdAt` is the SEED's fixed
 *     timestamp, not the run's — a wall-clock value would break exactly the
 *     determinism the artifact is supposed to prove.)
 *
 * Node-only on purpose: it reads and writes files. Like `./load` and
 * `./validate`, it is reached by the generator script and the suite — never by
 * the application (which is why the JSON artifact is not in any bundle).
 *
 * Generated by `npm run gen:dataset` (see `scripts/write-dataset.mjs`).
 */
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { validateDataset } from "@/domains/demo/backup";
import { DEMO_LIBRARY_ASSET_FILE, DEMO_LIBRARY_ASSET_ID, demoLibraryFileBytes } from "@/domains/demo/librarySeed";
import { DEMO_GALLERY_PHOTOS } from "@/domains/demo/gallerySeed";
import { SEED_DATE } from "@/domains/demo/schedulingSeed";
import { createSeedDataset, SEED_TIMESTAMP, SEED_VERSION } from "@/domains/demo/seed";
import {
  DATASET_ARTIFACT_DIR,
  DATASET_ASSETS_DIR,
  DATASET_MANIFEST_FILE,
  DATASET_SCHEMA_FILE,
  DATASET_SCHEMA_VERSION,
  canonicalDatasetJson,
  isCollectionName,
  memberFileName,
} from "./schema";
import { validateDatasetArtifact } from "./validate";
import type { DatasetAssetRecord, DatasetManifest } from "./schema";
import type { DemoDataset } from "@/domains/demo/types";

/** One text file of the artifact — artifact-relative path plus its contents. */
export interface ArtifactFile {
  path: string;
  contents: string;
}

export interface DatasetArtifactBuild {
  files: ArtifactFile[];
  manifest: DatasetManifest;
  dataset: DemoDataset;
}

export interface WriteReport {
  dir: string;
  files: number;
  bytes: number;
  datasetSha256: string;
  removed: string[];
}

/** Pretty-printed JSON, with the trailing newline every text file should have. */
function jsonFile(value: unknown): string {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function sha256(bytes: Uint8Array | string): string {
  return createHash("sha256").update(bytes).digest("hex");
}

/**
 * The repository path a bundled asset's URL points at.
 *
 * The showcase photographs are imported as URLs (`@/assets/images/hall.jpg`).
 * Under the tooling that generates the artifact (Vite dev/SSR — which is how
 * vitest and the generator script load these modules) that URL IS the source
 * path: `/src/assets/images/hall.jpg`. In a production build it is a hashed
 * output path instead, where the source file cannot be named — so this refuses
 * to guess and names the problem instead.
 */
export function assetSourcePath(url: string): string {
  const path = url.split("?")[0].replace(/^\//, "");
  if (!path.startsWith("src/")) {
    throw new Error(
      `cannot resolve the source file of the bundled asset 「${url}」 — the artifact must be generated through Vite (dev/SSR), where a bundled asset's URL is its source path`,
    );
  }
  return path;
}

/**
 * The byte source behind every `media` row of the dataset.
 *
 * Fail-closed: a media row this generator cannot locate bytes for is an error,
 * not a silently skipped asset. A dataset that names a file must be able to say
 * where that file is.
 */
export function datasetAssetRecords(dataset: DemoDataset = createSeedDataset()): DatasetAssetRecord[] {
  const photos = new Map(DEMO_GALLERY_PHOTOS.map((photo) => [photo.mediaId, photo]));
  const records: DatasetAssetRecord[] = [];

  for (const row of dataset.media) {
    if (row.id === DEMO_LIBRARY_ASSET_ID) {
      // Materialized: these bytes used to live inside `librarySeed.ts`.
      const bytes = new Uint8Array(demoLibraryFileBytes());
      records.push({
        id: row.id,
        kind: "document",
        filename: row.filename,
        mimeType: row.mimeType,
        sizeBytes: bytes.byteLength,
        // The artifact path is declared by the module that owns the file.
        file: DEMO_LIBRARY_ASSET_FILE,
        sha256: sha256(bytes),
      });
      continue;
    }

    const photo = photos.get(row.id);
    if (!photo) {
      throw new Error(
        `the dataset's media row 「${row.id}」 (${row.filename}) has no byte source: add it to the seed's asset modules before generating the artifact`,
      );
    }
    // Referenced: these bytes already ship from `src/assets/images/`.
    const sourcePath = assetSourcePath(photo.url);
    const bytes = readFileSync(join(process.cwd(), sourcePath));
    records.push({
      id: row.id,
      kind: "image",
      filename: row.filename,
      mimeType: row.mimeType,
      sizeBytes: bytes.byteLength,
      sourcePath,
      sha256: sha256(bytes),
    });
  }

  return records;
}

/** The generated shape document: which members exist, and which shape each has. */
export function datasetSchemaDocument(keyOrder: readonly string[]): Record<string, unknown> {
  return {
    $schema: "http://json-schema.org/draft-07/schema#",
    title: "ava sample dataset",
    description:
      "Shape of data/dataset/*.json: every top-level member the dataset must carry, its array/object nature, and no extra members. Row-level shape is the domain entity types (one model, never two) and referential integrity is checked by src/dataset/validate.ts — neither is duplicated here, so this document cannot drift from them.",
    type: "object",
    required: [...keyOrder],
    additionalProperties: false,
    properties: Object.fromEntries(
      keyOrder.map((name) => [
        name,
        isCollectionName(name) ? { type: "array", items: { type: "object" } } : { type: "object" },
      ]),
    ),
  };
}

/** Builds every file of the artifact, in memory, deterministically. */
export function buildDatasetArtifact(): DatasetArtifactBuild {
  const dataset = createSeedDataset();
  const keyOrder = Object.keys(dataset);
  const assets = datasetAssetRecords(dataset);

  const files: ArtifactFile[] = [];
  const members: DatasetManifest["members"] = {};
  const counts: DatasetManifest["counts"] = {};

  for (const name of keyOrder) {
    const contents = jsonFile(dataset[name as keyof DemoDataset]);
    const file = memberFileName(name);
    files.push({ path: file, contents });
    members[name] = {
      file,
      kind: isCollectionName(name) ? "collection" : "singleton",
      sha256: sha256(contents),
    };
    counts[name] = isCollectionName(name) ? (dataset[name as keyof DemoDataset] as unknown[]).length : 1;
  }

  // The materialized library document — the demo file's real bytes, written as
  // TEXT: `?raw` reads them back into the runtime, so the file and the served
  // bytes are one thing instead of two copies.
  const library = assets.find((asset) => asset.file);
  if (library) {
    files.push({
      path: library.file as string,
      contents: new TextDecoder().decode(new Uint8Array(demoLibraryFileBytes())),
    });
  }

  const assetList = jsonFile(assets);
  files.push({ path: `${DATASET_ASSETS_DIR}/assets.json`, contents: assetList });

  const schemaDocument = jsonFile(datasetSchemaDocument(keyOrder));
  files.push({ path: DATASET_SCHEMA_FILE, contents: schemaDocument });

  const manifest: DatasetManifest = {
    schemaVersion: DATASET_SCHEMA_VERSION,
    datasetVersion: SEED_VERSION,
    createdAt: SEED_TIMESTAMP,
    label: "Sample academy dataset",
    seedDate: SEED_DATE,
    source: "src/domains/demo/seed.ts#createSeedDataset()",
    keyOrder,
    counts,
    members,
    datasetSha256: sha256(canonicalDatasetJson(dataset)),
    assets: { file: `${DATASET_ASSETS_DIR}/assets.json`, count: assets.length, sha256: sha256(assetList) },
    schema: { file: DATASET_SCHEMA_FILE, sha256: sha256(schemaDocument) },
    integrity: { validator: "src/domains/demo/backup.ts#validateDataset()", issues: validateDataset(dataset).length },
  };
  files.push({ path: DATASET_MANIFEST_FILE, contents: jsonFile(manifest) });

  return { files, manifest, dataset };
}

/**
 * Writes the artifact and verifies what it wrote.
 *
 * Stale files from a previous shape are removed (only inside the artifact
 * directory, only files the manifest does not account for) and reported — a
 * generator whose directory accumulates leftovers stops being able to prove
 * anything. Afterwards the artifact is validated with the same validator an
 * importer would run; a single issue throws rather than reporting success.
 */
export function writeDatasetArtifact(dir: string = DATASET_ARTIFACT_DIR): WriteReport {
  const build = buildDatasetArtifact();
  const expected = new Set(build.files.map((file) => file.path));

  mkdirSync(join(dir, DATASET_ASSETS_DIR), { recursive: true });
  mkdirSync(join(dir, "schema"), { recursive: true });

  const removed: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isFile()) continue;
    if (!expected.has(entry.name)) {
      rmSync(join(dir, entry.name));
      removed.push(entry.name);
    }
  }
  for (const entry of readdirSync(join(dir, DATASET_ASSETS_DIR), { withFileTypes: true })) {
    if (!entry.isFile()) continue;
    if (!expected.has(`${DATASET_ASSETS_DIR}/${entry.name}`)) {
      rmSync(join(dir, DATASET_ASSETS_DIR, entry.name));
      removed.push(`${DATASET_ASSETS_DIR}/${entry.name}`);
    }
  }

  let bytes = 0;
  for (const file of build.files) {
    const path = join(dir, file.path);
    writeFileSync(path, file.contents, "utf8");
    bytes += Buffer.byteLength(file.contents, "utf8");
  }

  const issues = validateDatasetArtifact(dir);
  if (issues.length > 0) {
    throw new Error(
      `the artifact written to ${dir} does not validate:\n${issues.map((issue) => `  - [${issue.code}] ${issue.message}`).join("\n")}`,
    );
  }

  return { dir, files: build.files.length, bytes, datasetSha256: build.manifest.datasetSha256, removed };
}
